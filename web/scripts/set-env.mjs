// Writes src/environments/env.ts from NG_APP_* variables at build time.
// Sources, in priority order: process env, web/.env, repo-root .env.
// With --local it writes env.local.ts instead, pointing at the local Supabase stack
// (`npx supabase start`); the `local` build configuration swaps it in. Used by
// `npm run start:local` and Playwright, so they never touch the env.ts of `npm start`.
// Refuses to embed a Supabase service-role/secret key in the frontend bundle.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { loadEnv, webDir } from './load-env.mjs';
import { localStatus } from './supabase-cli.mjs';

const local = process.argv.includes('--local');
const outFile = resolve(webDir, `src/environments/${local ? 'env.local.ts' : 'env.ts'}`);
const env = loadEnv();

function localStack() {
  const status = localStatus();
  if (!status) {
    console.error('set-env: local Supabase is not running. Start it with `npm run db:start`.');
    process.exit(1);
  }
  return { url: status.api.origin, anonKey: status.anonKey };
}

const stack = local ? localStack() : undefined;
const supabaseUrl = stack?.url ?? env.NG_APP_SUPABASE_URL ?? '';
const supabaseAnonKey = stack?.anonKey ?? env.NG_APP_SUPABASE_ANON_KEY ?? '';
// PrimeUI Community License key; empty shows PrimeNG's license notice.
const primeuiLicense = env.NG_APP_PRIMEUI_LICENSE ?? '';

function isSecretKey(key) {
  if (key.startsWith('sb_secret_')) return true;
  const payload = key.split('.')[1];
  if (!payload) return false;
  try {
    return JSON.parse(Buffer.from(payload, 'base64url').toString()).role === 'service_role';
  } catch {
    return false;
  }
}

if (isSecretKey(supabaseAnonKey)) {
  console.error(
    'set-env: NG_APP_SUPABASE_ANON_KEY is a service-role/secret key. Use the anon (publishable) key.',
  );
  process.exit(1);
}

if (!supabaseUrl || !supabaseAnonKey) {
  // Cloudflare builds set WORKERS_CI=1 (Workers) or CF_PAGES=1 (Pages); a production
  // deploy without config must fail.
  if (env.WORKERS_CI || env.CF_PAGES) {
    console.error('set-env: NG_APP_SUPABASE_URL and NG_APP_SUPABASE_ANON_KEY must be set.');
    process.exit(1);
  }
  console.warn('set-env: Supabase variables not set; the app will build but cannot connect.');
}

const source = (url, anonKey) => `// Generated by scripts/set-env.mjs. Do not edit or commit.
export const env = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(anonKey)},
  primeuiLicense: ${JSON.stringify(primeuiLicense)},
};
`;

// The folder holds only these git-ignored files, so it is missing in a fresh checkout.
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, source(supabaseUrl, supabaseAnonKey));

// The local build still compiles env.ts before replacing it, so make sure one exists.
const devFile = resolve(webDir, 'src/environments/env.ts');
if (local && !existsSync(devFile)) writeFileSync(devFile, source('', ''));
